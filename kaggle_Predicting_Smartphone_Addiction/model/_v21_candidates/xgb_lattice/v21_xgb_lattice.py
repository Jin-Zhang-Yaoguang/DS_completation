#!/usr/bin/env python3
"""V21 candidate: strict out-of-fold exact/lattice target-frequency XGBoost.

Leakage contract
----------------
1. ``id`` and ``addicted_label`` are removed before any feature builder runs.
2. For an outer fold, target statistics for outer-train rows are generated by
   an inner StratifiedKFold. Outer-valid and test rows are mapped only from the
   outer-train labels.
3. Combined train+test frequency features use key codes only. No target array is
   accepted by that code path.
4. XGBoost uses a fixed number of rounds. Outer-valid labels evaluate the model
   but never choose a checkpoint.

The default command is the full five-fold job. Use ``--smoke`` for the small,
fast pipeline and leakage-mutation audit used before a full retrain.
"""

